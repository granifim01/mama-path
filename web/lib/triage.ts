const LEVEL_LABELS: Record<TriageLevel, string> = {
  emergency: "Немедленно — звоните 103",
  urgent: "Срочно — нужна помощь сегодня",
  doctor: "Обсудите с врачом",
  observe: "Не срочно",
};

export function triageQuery(input: string): TriageResult {
  const text = input.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ");
  const textYo = input.toLowerCase().replace(/\s+/g, " ");

  for (const rule of RULES) {
    if (rule.patterns.some((p) => p.test(text) || p.test(textYo))) {
      const { patterns: _patterns, ...result } = rule;
      return result;
    }
  }

  return {
    level: "doctor",
    title: "Нужна консультация специалиста",
    advice: "Мы не нашли точного совпадения. Это не диагноз — только ориентир.",
    action: "Опишите симптомы врачу. Если состояние ухудшается — звоните 103.",
  };
}

export function levelLabel(level: TriageLevel): string {
  return LEVEL_LABELS[level];
}
